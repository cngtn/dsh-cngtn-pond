/**
 * build.mjs — inlines `src/` and the vendored fonts into a single `client.js`.
 *
 * The shell evaluates `client.js` through `window.__ModuleLoader__`, and the
 * `require` it hands the factory only resolves the modules the shell already
 * hosts (React, the DSH client packages) — not relative paths inside a bundle.
 * So the client half has to be one self-contained file.
 *
 * That is why this build exists instead of a bundler: the output must stay plain,
 * readable ES2020 with no import statements, no `process` and no `import.meta`.
 * Each source module is wrapped in an IIFE that returns its own exports, so two
 * modules can each have a private `ramp` or `push` without colliding; only the
 * names a module actually exports are lifted into the shared scope, in
 * dependency order.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(here, p), 'utf8');

/** Every name a module exports, in the order it declares them. */
function exportedNames(src) {
  const names = [];
  for (const m of src.matchAll(/^export\s+(?:const|let|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    names.push(m[1]);
  }
  for (const m of src.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const part of m[1].split(',')) {
      const spec = part.trim();
      if (spec === '') continue;
      const as = spec.split(/\s+as\s+/);
      names.push((as[1] ?? as[0]).trim());
    }
  }
  return [...new Set(names)];
}

/** Strip ES module syntax; the IIFE wrapper supplies the scope. */
function stripModuleSyntax(src) {
  return src
    .replace(/^import\s+[\s\S]*?from\s+'[^']+';\s*$/gm, '')
    .replace(/^export\s*\{[^}]*\};\s*$/gm, '')
    .replace(/^export\s+(const|let|function|class)\s/gm, '$1 ');
}

function wrap(name, src) {
  const names = exportedNames(src);
  const body = stripModuleSyntax(src);
  return `/* ── ${name} ─────────────────────────────────────────────────────────────── */
const __m_${name} = (() => {
${body}
return { ${names.join(', ')} };
})();
const { ${names.join(', ')} } = __m_${name};`;
}

const base64 = (p) => readFileSync(join(here, p)).toString('base64');



const modules = [
  ['world', read('src/world.js')],
  ['shape', read('src/shape.js')],
  ['renderer', read('src/renderer.js')],
  ['engine', read('src/engine.js')],
  ['tokens', read('src/tokens.js')],
  ['styles', read('src/styles.js')],
].map(([name, src]) => wrap(name, src));

const applySrc = stripModuleSyntax(read('src/apply.js'));

const client = `/**
 * @cngtn/dsh-cngtn-pond — Client half.
 *
 * Hand-written against the module-loader contract (the shell has no bundler):
 * it evaluates this file, the factory receives \`require\`, and the returned
 * module exports \`inject\` plus \`apply\`.
 *
 * This file is GENERATED by \`build.mjs\` from \`src/\`. Edit the sources, then run
 * \`npm run build\`. The output is checked in because the shell loads it directly
 * and cannot compile anything.
 *
 * What it does, in the order the site itself is layered:
 *
 *  1. A **token layer** stacked over the active theme through \`ctx.theme\`
 *     (\`overrideTokens\`). This is the sanctioned third-party-theme extension
 *     point: it replaces the \`--dsw-*\` alias and static palettes with the
 *     paper-and-ink system, a tighter shape ladder, true (non-squircle) corners,
 *     a monospace type ramp, opaque paper menus instead of acrylic, and the koi
 *     vermilion as the single accent — for light and dark alike, so the user's
 *     Light/Dark preference keeps working.
 *  2. A **stylesheet** for the four things a token cannot express: the vendored
 *     Geist faces, the canvas layer, the transparency chain that lets the pond
 *     show through the frame, and the site's underline-only link treatment.
 *  3. A **canvas** behind the shell, running the pond: koi with a 20-node spine,
 *     burst-and-coast tail beats, curiosity toward the pointer, food on click,
 *     startle on a fast swipe, depth dives, and an ASCII raster that etches every
 *     fish into the same glyph grid as the interface.
 *
 * All three are registered inside \`ctx.effect\`, so disabling the plugin removes
 * the token layer, the stylesheet and the canvas, and the GUI returns to its
 * stock design.
 */
window.__ModuleLoader__.load({
  id: '@cngtn/dsh-cngtn-pond',
  factory: (require) => {
    const module = { exports: {} };
    const exports = module.exports;

// The theme sets no font family, so no webfont is inlined.


${modules.join('\n\n')}

/* ── apply ──────────────────────────────────────────────────────────────── */
${applySrc}

    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  },
});
`;

writeFileSync(join(here, 'client.js'), client, 'utf8');
const kb = (Buffer.byteLength(client) / 1024).toFixed(1);
console.log(`client.js written — ${kb} KB`);